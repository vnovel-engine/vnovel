#!/usr/bin/env python3
"""Generate the engine symbol-prefix headers.

Why
---

ONScripter-EN and PONScripter are forks of the same codebase, so they define
identical C++ class names (ScriptHandler, AnimationInfo, ScriptParser, ...).
Linked into one object file that is a multiple-definition error: both .so
modules today exist only to keep them apart in separate symbol tables.

Linking all three engines into ONE core needs those names separated, and C++
makes that cheap: a mangled name is derived from the class name, so one
#define per class renames every method, vtable and typeinfo at once. Measured
on a real object, 10 defines move all 145 symbols of a translation unit.

How
---

The names below are the ones that actually collide, taken from
`nm --defined-only` over both engines' objects (see the COLLIDING set in the
commit message). Only the colliding names are listed: renaming more would
churn the diff for no benefit, and renaming less leaves duplicate symbols.

The rename is a pure preprocessor rename gated behind ONS_SYMBOL_PREFIX /
PON_SYMBOL_PREFIX, exactly like sdl-vendored.h. Nothing that is part of the
core's own C ABI is renamed: the core calls the engines through engine_cabi.h,
and those symbols (ons_engine_vtable, pons_engine_vtable, the free functions
it names) are deliberately absent from these lists.

Usage:
    tools/gen-engine-symbol-prefix.py            # writes both headers
    tools/gen-engine-symbol-prefix.py --check    # verify they are current
"""

import argparse
import os
import subprocess
import sys

# Names that collide between the ONScripter-EN and PONScripter objects.
#
# Derived from the objects themselves, not invented: each line below was
# reported by linking ScriptHandler.ons.o against ScriptHandler.pons.o and
# reading the multiple-definition errors, then extended over every shared
# translation unit. Re-derive after an upstream merge with:
#
#   nm --defined-only build/unix/deps/onscripter-en/*.o |
#     awk '$2 ~ /[TDBRWV]/ {print $3}' | sort -u > ons.txt
#   nm --defined-only build/unix/deps/ponscripter/src/*.o |
#     awk '$2 ~ /[TDBRWV]/ {print $3}' | sort -u > pons.txt
#   comm -12 ons.txt pons.txt | c++filt   # -> the names below
CLASSES = [
    # Text and layout
    "AnimationInfo",
    "Fontinfo",
    "DirtyRect",
    # Script parsing and state
    "ScriptHandler",
    "ScriptParser",
    # Archive readers
    "BaseReader",
    "DirectReader",
    "SarReader",
    "NsaReader",
    # Path handling
    "DirPaths",
]

# Free functions and file-scope data that also collide. A static function has
# internal linkage and cannot collide, but these are not all static upstream,
# so they are renamed defensively — the cost is one line each.
FUNCTIONS = [
    # Audio callbacks, registered by address with SDL_mixer/SMPEG/libmad
    "musicCallback",
    "waveCallback",
    "mp3callback",
    "oggcallback",
    "cdaudioCallback",
    "timerCallback",
    "MAD_WRAPPER_new",
    "MAD_WRAPPER_new_rwops",
    "MAD_WRAPPER_delete",
    "MAD_WRAPPER_play",
    "MAD_WRAPPER_playAudio",
    "MAD_WRAPPER_stop",
    "MAD_WRAPPER_setvolume",
    "MAD_WRAPPER_error",
    # Input translation
    "transJoystickAxis",
    "transJoystickButton",
    # Vorbis decode helper
    "decodeOggVorbis",
]

# File-scope data that collides. `header` is too common a name to leave alone
# once two trees share a symbol table.
DATA = [
    "ext_music_play_once_flag",
    "timer_cdaudio_id",
    "header",
]

HEADER_TEMPLATE = """\
/* {fname} — GENERATED by tools/gen-engine-symbol-prefix.py. Do not edit.
 *
 * Renames {engine}'s internal C++ symbols to a private prefix so that
 * ONScripter-EN, PONScripter and KiriKiri can be linked into ONE core.
 *
 * The two ONScripter forks define the same class names; linked together that
 * is a multiple-definition error (see the generator for the derivation). A
 * mangled name is derived from the class name, so one #define per class
 * renames every method, vtable and typeinfo at once.
 *
 * Opt-in, like sdl-vendored.h: it applies only where the build defines
 * {gate}. Nothing in the core's own C ABI (engine_cabi.h) is renamed.
 */

#ifndef {guard}
#define {guard}

#ifdef {gate}
{defines}
#endif /* {gate} */

#endif /* {guard} */
"""


def render(engine, gate, guard, fname, prefix):
    defines = []
    for name in CLASSES + FUNCTIONS + DATA:
        defines.append("#define {:<28} {}{}".format(name, prefix, name))
    return HEADER_TEMPLATE.format(
        fname=fname, engine=engine, gate=gate, guard=guard,
        defines="\n".join(defines))


def targets(root):
    """The two headers and their contents."""
    return [
        (os.path.join(root, "ons-symbol-prefix.h"),
         render("ONScripter-EN", "ONS_SYMBOL_PREFIX", "ONS_SYMBOL_PREFIX_H",
                "ons-symbol-prefix.h", "ONS_")),
        (os.path.join(root, "pons-symbol-prefix.h"),
         render("PONScripter", "PON_SYMBOL_PREFIX", "PON_SYMBOL_PREFIX_H",
                "pons-symbol-prefix.h", "PON_")),
    ]


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if the headers differ from the generator")
    ap.add_argument("--root", default=".",
                    help="where to write (default: the repo root)")
    args = ap.parse_args()

    stale = []
    for path, content in targets(args.root):
        current = None
        if os.path.exists(path):
            current = open(path, encoding="utf-8").read()
        if current == content:
            print(f"{path}: up to date")
            continue
        if args.check:
            stale.append(path)
            print(f"{path}: STALE", file=sys.stderr)
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)
            print(f"{path}: written")

    if stale:
        print("run tools/gen-engine-symbol-prefix.py to regenerate", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
