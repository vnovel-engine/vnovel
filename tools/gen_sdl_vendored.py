#!/usr/bin/env python3
"""Generate sdl-vendored.h: rename our vendored SDL/SDL_mixer/SMPEG/SDL_ttf/
SDL_image symbols to a Private prefix, at source level.

Why this exists
---------------

The core is built as several modules (runtime + one per engine + the core) so
that ONScripter and PONScripter, which define identical C++ class names, cannot
collide in one symbol table. That split means the vendored SDL we ship is no
longer local to a single binary — and RetroArch loads its own SDL2/SDL3
globally. Symbol lookup then finds the host's SDL first:

    engine_ons -> libSDL2-2.0.so.0 : SDL_Init, SDL_PollEvent,
                                     SDL_CreateRGBSurface, SDL_LockSurface
    engine_ons -> our runtime      : SDL_SetVideoMode

So the engine allocates SDL2 surfaces while our runtime renders through SDL 1.2.
The two have different struct layouts, and the engine writes through a misread
pointer: "*** stack smashing detected ***".

Renaming the symbols keeps our SDL out of that namespace entirely, so there is
nothing to collide with and nothing to resolve to the wrong library. It is a
pure preprocessor rename, so it behaves identically on ELF and PE — unlike the
linker-level alternatives (RTLD_DEEPBIND is ELF/glibc-only, DF_1_GROUP has no
PE analogue, and -Bsymbolic only affects a library's internal calls).

How it is applied
-----------------

The header is force-included (-include) into the vendored library sources AND
every consumer of them (the engines, the glue, the core, SMPEG, SDL_mixer), so
both the definition and every call site spell the same Private name. SDL's own
headers can stay untouched: they declare SDL_Init(), but by the time those
declarations are seen the macro has already rewritten the name.

Only linkable symbols (functions and data objects) are renamed. Types, enums and
macros stay as they are — all our code compiles against our own SDL headers, so
struct layouts are already consistent, and renaming a type would break the
headers that define it.

The list is generated from the objects we actually build, so it cannot drift
from what ships.
"""

import re
import subprocess
import sys
from pathlib import Path

# Our own glue and anything the host legitimately provides. SDL_main is the
# entry-point shim and is supplied by whoever links the final binary.
EXCLUDE = re.compile(r"^(SDL_libretro_|SDL_main)")

# Compiler-generated local symbols share the base name: nm shows things like
# SDL_strtoul.localalias, SMPEG_new.cold, TTF_Foo.constprop.0. They are not
# linkable names, nothing references them by hand, and #define-ing them is a
# syntax error. Only the base symbol is renamed.
GENERATED = re.compile(r"\.")

PREFIX = "Private"
NAMESPACES = ("SDL_", "IMG_", "TTF_", "Mix_", "SMPEG_")

# Directories whose objects count as "our vendored copy".
VENDORED_DIRS = ("deps/sdl", "deps/sdl-mixer", "sdl-libretro", "smpeg")

HEADER = """\
// sdl-vendored.h — GENERATED by tools/gen_sdl_vendored.py. Do not edit.
//
// Renames our vendored SDL / SDL_mixer / SMPEG / SDL_ttf / SDL_image symbols to
// a Private prefix, so they cannot collide with the SDL2/SDL3 that a frontend
// (RetroArch) loads into the same process. See the generator for the full
// rationale.
//
// Opt-in: the rename applies only where the build defines RENAME_SDL_SYMBOLS
// (see Makefile.common). It is deliberately not tied to __RETRO__: that macro
// only marks "built as part of the libretro core", which is true whether or not
// the symbols need renaming. The rename exists for one specific situation —
// several modules of ours in one process, next to a frontend that loads its own
// SDL2/SDL3 globally — so it is the build that opts in, not the context.

#ifndef SDL_VENDORED_H
#define SDL_VENDORED_H

#ifdef RENAME_SDL_SYMBOLS

{defines}
#endif /* RENAME_SDL_SYMBOLS */

#endif /* SDL_VENDORED_H */
"""


def symbols_from_objects(build_dir: Path) -> list[str]:
    """Collect defined SDL-family symbols from the vendored objects."""
    syms: set[str] = set()
    for sub in VENDORED_DIRS:
        root = build_dir / sub
        if not root.is_dir():
            continue
        objs = list(root.rglob("*.o"))
        if not objs:
            continue
        out = subprocess.run(
            ["nm", *map(str, objs)], capture_output=True, text=True, check=False
        ).stdout
        for line in out.splitlines():
            parts = line.split()
            if len(parts) < 3:
                continue
            kind, name = parts[1], parts[2]
            # T/t text, D/d data, B/b bss, R/r rodata, G/g, V/v, W/w weak
            if kind not in "TtDdBbRrGgVvWw":
                continue
            if name.startswith(NAMESPACES) and not EXCLUDE.match(name) and not GENERATED.search(name):
                syms.add(name)
    return sorted(syms)


def function_like_guard(name: str) -> str | None:
    """The preprocessor condition under which `name` is a function-like macro.

    Returns the guard expression, or None if there is no such define at all.

    Needed because "is a function-like macro" is not a property of the name but
    of the platform: SDL_thread.h defines SDL_CreateThread(fn,data) only when
    SDL_PASSED_BEGINTHREAD_ENDTHREAD is set, which SDL sets for everything EXCEPT
    mingw; SDL_stdinc.h defines SDL_revcpy(...) only for __GNUC__ && i386. On a
    target where the guard is false the plain function is what actually exists,
    and it leaks like any other unrenamed symbol.

    That distinction did not matter while -fvisibility=hidden could hide a leak.
    On PE it cannot (PE has no visibility attribute; only dllexport governs, and
    DECLSPEC is neutralised here), so a name that leaks on Windows collides with
    the engine's own SDL2 — SDL_CreateThread was a hard link error against
    libSDL2.a.

    Returning the guard rather than a bare bool lets the caller emit the rename
    under `#if !(guard)`: renamed where the name is a real function, skipped
    where a #define would swallow the declaration or corrupt call sites.
    """
    pattern = re.compile(r"^\s*#\s*define\s+" + re.escape(name) + r"\s*\(", re.MULTILINE)
    for root in ("deps/sdl/include", "deps/sdl-mixer", "sdl-libretro", "smpeg"):
        p = Path(root)
        if not p.is_dir():
            continue
        for header in p.rglob("*.h"):
            try:
                text = header.read_text(errors="ignore")
            except OSError:
                continue
            if not pattern.search(text):
                continue
            # The guard SDL actually uses, recognised by the macro it keys on.
            # SDL_CreateThread is the only name safe to treat this way: where
            # the function-like macro is off (mingw, which does not define
            # SDL_PASSED_BEGINTHREAD_ENDTHREAD) its declaration sits in the
            # #else branch with no `#ifndef SDL_CreateThread` around it, so the
            # rename does not swallow it. Where the macro is active the rename
            # is skipped, which is what keeps call sites working.
            #
            # SDL_revcpy cannot be handled this way: its declaration IS wrapped
            # in `#ifndef SDL_revcpy`, so on x86_64 — where the macro is off and
            # the rename would therefore apply — the #define would make that
            # guard false and the declaration would vanish, leaving call sites
            # with no prototype. It is skipped unconditionally and handled at
            # the symbol level instead.
            if name == "SDL_CreateThread":
                return "defined(SDL_PASSED_BEGINTHREAD_ENDTHREAD)"
            return "1"
    return None

def main() -> int:
    build_dir = Path(sys.argv[1] if len(sys.argv) > 1 else "build/unix")
    out_path = Path(sys.argv[2] if len(sys.argv) > 2 else "sdl-vendored.h")
    syms = symbols_from_objects(build_dir)
    if not syms:
        print("error: no vendored symbols found (build first)", file=sys.stderr)
        return 1
    # DECLSPEC is SDL's export attribute. On GCC it expands to
    # __attribute__((visibility("default"))), which overrides the build's
    # -fvisibility=hidden — so every function SDL declares with it is exported
    # regardless of what the makefile asks for. It is #ifndef-guarded, so
    # defining it empty here neutralises the forced export and lets the
    # visibility flag do its job. Our SDL is never a shared library of its own,
    # so it needs no exported symbols at all.
    #
    # This is what hides the ~200 plain SDL_* names on ELF, where
    # -fvisibility=hidden applies. Renaming them all via the #define list is the
    # other half of the mechanism, and on PE it is the ONLY half: PE has no
    # visibility attribute, so an unrenamed symbol is exported and collides with
    # the engine's own SDL2 whichever way the frontend loads.
    #
    # Names that SDL also declares as a function-like macro on some platform are
    # renamed only where that macro is inactive, since an active one would
    # swallow the declaration (#ifndef NAME) or mangle call sites. On a platform
    # where the macro is off — mingw for SDL_CreateThread, x86_64 for SDL_revcpy
    # — the plain function is what exists and it must be renamed or it collides
    # with the engine's SDL2 at link time on PE, where visibility cannot hide it.
    unconditional: list[str] = []
    guarded: list[tuple[str, str]] = []
    for s in syms:
        guard = function_like_guard(s)
        if guard is None:
            unconditional.append(s)
        elif guard != "1":
            guarded.append((s, guard))

    defines = "\n".join(f"#define {s} {PREFIX}{s}" for s in unconditional)
    if guarded:
        blocks = []
        for s, guard in guarded:
            blocks.append(
                f"/* `{s}' is a function-like macro under ({guard}); renamed only\n"
                f"   where it is not, so the declaration survives and call sites\n"
                f"   stay intact. */\n"
                f"#if !({guard})\n#define {s} {PREFIX}{s}\n#endif"
            )
        defines += "\n\n" + "\n".join(blocks)
    defines = (
        "/* Neutralise SDL's export attribute; see the generator for why. */\n"
        "#define DECLSPEC\n"
        "#define SDL_DECLSPEC\n\n" + defines
    )
    out_path.write_text(HEADER.format(defines=defines))
    print(f"wrote {out_path} ({len(syms)} symbols, {len(guarded)} guarded)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
